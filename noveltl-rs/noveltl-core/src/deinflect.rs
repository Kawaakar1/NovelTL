//! Приведение спрягаемых форм японских глаголов и い-прилагательных к словарной форме.

use std::collections::HashSet;
use std::sync::OnceLock;

/// Правила «окончание → словарное (или промежуточное) окончание», не зависящие от ряда годан.
const RULES: &[(&str, &str)] = &[
    // вежливая форма -> основа на ます
    ("ました", "ます"), ("ません", "ます"), ("ませんでした", "ます"), ("ましょう", "ます"),
    // ichidan и неправильные
    ("ます", "る"), ("ました", "る"), ("ません", "る"), ("ない", "る"), ("よう", "る"), ("れば", "る"), ("て", "る"), ("た", "る"),
    ("たい", "る"), ("そう", "る"), ("られる", "る"), ("させる", "る"), ("せる", "る"), ("れる", "る"),
    ("しない", "する"), ("します", "する"), ("しよう", "する"), ("すれば", "する"), ("して", "する"),
    ("した", "する"), ("される", "する"), ("させる", "する"),
    ("こない", "くる"), ("きます", "くる"), ("こよう", "くる"), ("くれば", "くる"), ("きて", "くる"),
    ("きた", "くる"), ("こられる", "くる"),
    // годан: て/た-формы
    ("って", "う"), ("った", "う"), ("って", "つ"), ("った", "つ"), ("って", "る"), ("った", "る"),
    ("って", "く"), ("った", "く"), // 行く
    ("いて", "く"), ("いた", "く"), ("いで", "ぐ"), ("いだ", "ぐ"),
    ("んで", "ぬ"), ("んだ", "ぬ"), ("んで", "ぶ"), ("んだ", "ぶ"), ("んで", "む"), ("んだ", "む"),
    ("して", "す"), ("した", "す"),
    // ている / ちゃう и т.п. -> форма на て/で
    ("ている", "て"), ("ていた", "て"), ("ています", "て"), ("ていました", "て"), ("ていない", "て"),
    ("てる", "て"), ("てた", "て"), ("でいる", "で"), ("でいた", "で"), ("でいます", "で"),
    ("でいました", "で"), ("でる", "で"), ("でた", "で"),
    ("ちゃう", "て"), ("ちゃった", "て"), ("ちゃって", "て"), ("じゃう", "で"), ("じゃった", "で"), ("じゃって", "で"),
    // い-прилагательные (и たい)
    ("く", "い"), ("くて", "い"), ("かった", "い"), ("くない", "い"), ("くなかった", "い"),
    ("くなくて", "い"), ("ければ", "い"), ("さ", "い"), ("そう", "い"),
    ("なかった", "ない"), ("なくて", "ない"), ("たかった", "たい"),
];

/// Ряды годан: (словарное окончание, あ-, い-, え-, お-основа).
const ROWS: &[[&str; 5]] = &[
    ["う", "わ", "い", "え", "お"], ["く", "か", "き", "け", "こ"], ["ぐ", "が", "ぎ", "げ", "ご"],
    ["す", "さ", "し", "せ", "そ"], ["つ", "た", "ち", "て", "と"], ["ぬ", "な", "に", "ね", "の"],
    ["ぶ", "ば", "び", "べ", "ぼ"], ["む", "ま", "み", "め", "も"], ["る", "ら", "り", "れ", "ろ"],
];

fn rules() -> &'static Vec<(String, String)> {
    static R: OnceLock<Vec<(String, String)>> = OnceLock::new();
    R.get_or_init(|| {
        let mut v: Vec<(String, String)> = RULES.iter().map(|(a, b)| (a.to_string(), b.to_string())).collect();
        for [d, a, i, e, o] in ROWS {
            for s in ["ない", "れる", "せる"] { v.push((format!("{a}{s}"), d.to_string())); }
            for s in ["ます", "たい", "そう"] { v.push((format!("{i}{s}"), d.to_string())); }
            for s in ["ば", "る"] { v.push((format!("{e}{s}"), d.to_string())); }
            v.push((format!("{o}う"), d.to_string()));
        }
        v
    })
}

/// Возможные словарные формы слова (первым — само слово), без повторов. Для поиска в словаре.
pub fn deinflect(word: &str) -> Vec<String> {
    let mut out = vec![word.to_string()];
    let mut seen: HashSet<String> = out.iter().cloned().collect();
    let mut frontier = out.clone();
    for _ in 0..3 {
        let mut next = Vec::new();
        for w in &frontier {
            for (from, to) in rules() {
                if let Some(stem) = w.strip_suffix(from.as_str()) {
                    if stem.is_empty() && to.chars().count() == 1 { continue; }
                    let c = format!("{stem}{to}");
                    if seen.insert(c.clone()) { out.push(c.clone()); next.push(c); }
                }
            }
        }
        frontier = next;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn forms() {
        for (w, d) in [
            ("食べました", "食べる"), ("読んだ", "読む"), ("行った", "行く"), ("書いて", "書く"),
            ("話さない", "話す"), ("来ました", "来る"), ("しました", "する"), ("早くて", "早い"),
            ("寒かった", "寒い"), ("見られる", "見る"), ("待っています", "待つ"),
            ("食べさせられました", "食べる"),
        ] {
            assert!(deinflect(w).contains(&d.to_string()), "{w} -> {d}: {:?}", deinflect(w));
        }
        assert_eq!(deinflect("猫")[0], "猫");
    }
}
